import pg from 'pg';

export const tasksSchema = `CREATE TABLE IF NOT EXISTS tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  done INTEGER NOT NULL DEFAULT 0 CHECK (done IN (0, 1))
)`;

export function createPool() {
  const pool = new pg.Pool({
    max: 5,
    connectionTimeoutMillis: 750,
    idleTimeoutMillis: 10_000,
    query_timeout: 1_000,
    statement_timeout: 1_000
  });
  // Não registrar credenciais nem encerrar a API se uma conexão ociosa cair.
  pool.on('error', () => console.error(JSON.stringify({ level: 'error', message: 'Conexão PostgreSQL indisponível' })));
  return pool;
}
